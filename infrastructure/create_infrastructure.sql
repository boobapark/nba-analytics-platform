-- Roles

USE ROLE USERADMIN;

CREATE ROLE IF NOT EXISTS BASKETBALL_DBT_DEV;
CREATE ROLE IF NOT EXISTS BASKETBALL_ANALYST;

GRANT ROLE BASKETBALL_DBT_DEV TO ROLE SYSADMIN;
GRANT ROLE BASKETBALL_ANALYST TO ROLE SYSADMIN;


-- Warehouse

USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS BASKETBALL_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

GRANT USAGE ON WAREHOUSE BASKETBALL_WH TO ROLE BASKETBALL_DBT_DEV;
GRANT USAGE ON WAREHOUSE BASKETBALL_WH TO ROLE BASKETBALL_ANALYST;


-- Database & Schemas

