CREATE SCHEMA IF NOT EXISTS BASKETBALL_DEV.RAW;
CREATE SCHEMA IF NOT EXISTS BASKETBALL_DEV.STAGING;
CREATE SCHEMA IF NOT EXISTS BASKETBALL_DEV.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS BASKETBALL_DEV.MARTS;


-- Permissions DBT

GRANT USAGE ON DATABASE BASKETBALL_DEV
TO ROLE BASKETBALL_DBT_DEV;

GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE BASKETBALL_DEV
TO ROLE BASKETBALL_DBT_DEV;

GRANT ALL PRIVILEGES ON FUTURE SCHEMAS IN DATABASE BASKETBALL_DEV
TO ROLE BASKETBALL_DBT_DEV;


-- Permissions Analyst

GRANT USAGE ON DATABASE BASKETBALL_DEV
TO ROLE BASKETBALL_ANALYST;

GRANT USAGE ON SCHEMA BASKETBALL_DEV.MARTS
TO ROLE BASKETBALL_ANALYST;

GRANT SELECT ON FUTURE TABLES IN SCHEMA BASKETBALL_DEV.MARTS
TO ROLE BASKETBALL_ANALYST;

GRANT SELECT ON FUTURE VIEWS IN SCHEMA BASKETBALL_DEV.MARTS
TO ROLE BASKETBALL_ANALYST;


-- Csv FORMAT
USE DATABASE BASKETBALL_DEV;
