USE WAREHOUSE BASKETBALL_TRANSFORM_WH;
USE DATABASE BASKETBALL_DEV;
USE ROLE BASKETBALL_DBT_DEV;




show views like 'STG_TEAM';
SELECT *
FROM RAW.TEAM
ORDER BY RANDOM()
LIMIT 100;

SELECT COUNT(*) AS nb_lignes
FROM RAW.COMMON_PLAYER_INFO;

SELECT
    PERSON_ID,
    COUNT(*) AS nb_occurrences
FROM RAW.COMMON_PLAYER_INFO
GROUP BY PERSON_ID
HAVING COUNT(*) > 1;

SELECT
    COUNT(*) AS nb_lignes,
    SUM(CASE WHEN PERSON_ID IS NULL THEN 1 ELSE 0 END)
        AS id_manquants,
    SUM(CASE WHEN FIRST_NAME IS NULL THEN 1 ELSE 0 END)
        AS prenoms_manquants,
    SUM(CASE WHEN TEAM_ID IS NULL THEN 1 ELSE 0 END)
        AS team_id_manquants
FROM RAW.COMMON_PLAYER_INFO;